let currentLang = localStorage.getItem('orbriot_lang') || 'en';

function updateLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('orbriot_lang', lang);
  
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  
  document.querySelectorAll('[data-lang]').forEach(el => {
    const key = el.dataset.lang;
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  
  document.querySelectorAll('[data-lang-placeholder]').forEach(el => {
    const key = el.dataset.langPlaceholder;
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });
  
  const pageTitleKey = document.querySelector('[data-page-title]')?.dataset.pageTitle;
  if (pageTitleKey && translations[lang][pageTitleKey]) {
    document.title = `${translations[lang][pageTitleKey]} - ORBRIOT`;
  } else {
    document.title = lang === 'tr' ? 'ORBRIOT - Retro-Futuristic Brick Blast Oyunu' : 'ORBRIOT - Retro-Futuristic Brick Blast Game';
  }
  
  document.documentElement.lang = lang;
}

document.addEventListener('DOMContentLoaded', () => {
  updateLanguage(currentLang);
  
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      updateLanguage(btn.dataset.lang);
    });
  });
});
